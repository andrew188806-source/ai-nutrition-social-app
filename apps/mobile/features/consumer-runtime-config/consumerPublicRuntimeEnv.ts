//
// Expo's web export inlines `process.env.EXPO_PUBLIC_*` only where it appears as a literal member
// expression. At runtime the exported bundle's `process.env` holds nothing but NODE_ENV, so any
// indirect read — spreading `process.env`, `globalThis.process?.env`, or dynamic indexing — resolves
// every flag to undefined in the Stable Demo even when the build environment defines it (the dev
// server happens to expose them, which is why indirect reads looked correct locally). Every Consumer
// runtime composition therefore reads its public configuration from this module, and every name
// below is referenced literally so the bundler can inline it.
//
// Values are public by definition (EXPO_PUBLIC_*); nothing secret belongs here.

