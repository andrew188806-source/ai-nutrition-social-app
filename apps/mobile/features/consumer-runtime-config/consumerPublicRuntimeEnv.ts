// C-1B fail-closed rule. A LIVE Consumer composition is one whose identity is a real Supabase session
// (EXPO_PUBLIC_TASTKIND_CONSUMER_AUTH_SOURCE=supabase-live). In a live composition a data source whose
// flag is missing must resolve to disabled/unavailable — never to mock fixtures — because real user
// state must never be combined with invented data. Outside a live composition (no live identity at all:
// local demo preview, harnesses) the historical defaults are unchanged. An EXPLICIT "mock" value remains
// an explicit, auditable choice.
export function isLiveConsumerComposition(env: Readonly<Record<string, string | undefined>>): boolean {
  return env.EXPO_PUBLIC_TASTKIND_CONSUMER_AUTH_SOURCE === "supabase-live";
}

export function allowsImplicitMockSource(env: Readonly<Record<string, string | undefined>>): boolean {
  return !isLiveConsumerComposition(env);
}
